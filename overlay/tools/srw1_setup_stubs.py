#!/usr/bin/env python3
"""Emit link placeholders for the SRW1 *setup* build.

The one-click pack ships without any generated (ROM-derived) C. The setup
executable still links the hand-written runtime, which references
recompiled functions declared in funcs.h. This writes a never-called body
for each such declaration so the setup build links; SnesInit() refuses to
run game code in a setup build, and the real build replaces all of this
with the code generated locally from the player's own ROM.

Names that the hand-written sources already define are skipped.
"""
import argparse
import os
import re
import sys

DECL = re.compile(r"^(void|RecompReturn)\s+([A-Za-z_]\w*)\s*\(\s*CpuState\s*\*\s*cpu\s*\)\s*;", re.M)


def defined_in_sources(src_root):
    names = set()
    pat = re.compile(r"^\s*(?:static\s+)?(?:void|RecompReturn)\s+([A-Za-z_]\w*)\s*\(\s*CpuState\s*\*\s*\w*\s*\)\s*\{?\s*$", re.M)
    for dp, dn, fn in os.walk(src_root):
        dn[:] = [d for d in dn if not d.startswith(("gen", ".gen"))]
        for f in fn:
            if f.endswith(".c"):
                try:
                    txt = open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()
                except OSError:
                    continue
                names.update(pat.findall(txt))
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--funcs-h", action="append", required=True)
    ap.add_argument("--src-root", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    decls = {}
    for h in a.funcs_h:
        if os.path.isfile(h):
            for ret, name in DECL.findall(open(h, encoding="utf-8", errors="replace").read()):
                decls.setdefault(name, ret)
    skip = defined_in_sources(a.src_root)
    out = ["/* Generated by tools/srw1_setup_stubs.py for the setup build only. */",
           "#include <stdlib.h>", "#include \"cpu_state.h\"", "",
           "static void srw1_setup_no_game(void) { abort(); }", ""]
    n = 0
    for name in sorted(decls):
        if name in skip:
            continue
        ret = decls[name]
        if ret == "void":
            out.append("void %s(CpuState *cpu) { (void)cpu; srw1_setup_no_game(); }" % name)
        else:
            out.append("RecompReturn %s(CpuState *cpu) { (void)cpu; srw1_setup_no_game(); return (RecompReturn)0; }" % name)
        n += 1
    tmp = a.out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    os.replace(tmp, a.out)
    print("srw1_setup_stubs: %d placeholders" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
